#!/usr/bin/env sh
# Запуск в production (Render).
#
# Shell на бесплатном плане Render недоступен, поэтому миграции и загрузка
# контента выполняются автоматически при старте сервиса.

set -e

if [ -z "$DATABASE_URL" ]; then
  echo "[start] ОШИБКА: не задана переменная DATABASE_URL"
  exit 1
fi

# База может подниматься дольше веб-сервиса (особенно после простоя на
# бесплатном плане), поэтому первые попытки подключения могут не пройти.
echo "[start] применяю миграции"
attempt=1
until npx prisma migrate deploy; do
  if [ "$attempt" -ge 10 ]; then
    echo "[start] ОШИБКА: база недоступна после $attempt попыток"
    exit 1
  fi
  echo "[start] база недоступна, попытка $attempt из 10, жду 10 секунд"
  attempt=$((attempt + 1))
  sleep 10
done

# Контент загружается в фоне: на удалённой базе это занимает минуты, а порт
# нужно открыть сразу, иначе платформа сочтёт сервис зависшим и прервёт деплой.
# Seed идемпотентен, поэтому безопасен при каждом рестарте; его сбой не должен
# ронять приложение — оно поднимется и покажет пустое состояние.
(
  echo "[seed] загружаю контент"
  if npm run seed; then
    echo "[seed] контент загружен"
  else
    echo "[seed] ВНИМАНИЕ: загрузка контента не удалась, подробности выше"
  fi
) &

echo "[start] запускаю приложение на порту ${PORT:-3000}"
exec npx next start -p "${PORT:-3000}"
