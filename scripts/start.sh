#!/usr/bin/env sh
# Запуск в production (Render).
#
# Shell на бесплатном плане Render недоступен, поэтому миграции и загрузка
# контента выполняются автоматически при старте сервиса.

set -e

echo "[start] применяю миграции"
npx prisma migrate deploy

# Seed идемпотентен: существующие записи обновляются, дубликаты не создаются.
# Ошибка загрузки контента не должна ронять сервис — приложение поднимется
# и покажет пустое состояние, а причина останется в логах.
echo "[start] загружаю контент"
if npm run seed; then
  echo "[start] контент загружен"
else
  echo "[start] ВНИМАНИЕ: загрузка контента не удалась, сервис стартует без неё"
fi

echo "[start] запускаю приложение на порту ${PORT:-3000}"
exec npx next start -p "${PORT:-3000}"
